import dotenv from "dotenv";
import {basename,resolve} from "node:path";
dotenv.config({path:process.env.ENV_FILE||resolve(process.cwd(),basename(process.cwd())==="server"?"../.env":".env")});
import express from "express";
import cors from "cors";
import helmet from "helmet";
import rateLimit from "express-rate-limit";
import {router} from "./http/routes.js";
import {authRouter} from "./http/authRoutes.js";
import {derivRouter} from "./http/derivRoutes.js";
import {sessionRouter} from "./http/sessionRoutes.js";
const app=express();
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_ORIGIN||"http://localhost:5173"}));
app.use(express.json({limit:"32kb"}));
app.use("/api/auth",rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}),authRouter);
app.use("/api/deriv",rateLimit({windowMs:60*1000,limit:20,standardHeaders:true,legacyHeaders:false}),derivRouter);
app.use("/api/sessions",sessionRouter);
app.use("/api",router);
app.use((err,req,res,next)=>{console.error(err.message);res.status(err.status||500).json({error:err.status?err.message:"Server error. Check server logs and configuration."});});
const port=Number(process.env.PORT||4000);
app.listen(port,()=>console.log(`Deriv Digit Engine API on ${port}; live trading ${process.env.ENABLE_LIVE_TRADING==="true"?"ENABLED BY ADMIN":"DISABLED"}`));
